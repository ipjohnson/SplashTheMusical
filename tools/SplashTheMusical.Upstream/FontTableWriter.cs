using System.Globalization;
using System.Text;

namespace SplashTheMusical.Upstream;

/// <summary>A font family the default text measurer ships tables for.</summary>
/// <param name="Name">The family name.</param>
/// <param name="Aliases">Other CSS family names measured with the family, such as fonts with the same widths.</param>
/// <param name="Files">The regular, bold, italic and bold italic font files, relative to the repository.</param>
public sealed record FontFamily(string Name, IReadOnlyList<string> Aliases, IReadOnlyList<string> Files);

/// <summary>Writes <c>FontTables.g.cs</c>, the advance widths and kerning of each face of each family as static data.</summary>
public static class FontTableWriter
{
	/// <summary>
	/// The families the default measurer ships. Liberation Sans is the font tools/oracle bundles. Its widths match Arial's,
	/// and Arial is in mermaid's default font list. The first family is the generic sans-serif one.
	/// </summary>
	public static readonly IReadOnlyList<FontFamily> Families =
	[
		new(
			"Liberation Sans",
			["Arial", "Arimo", "Helvetica", "sans-serif"],
			[
				"tools/oracle/fonts/LiberationSans-Regular.ttf",
				"tools/oracle/fonts/LiberationSans-Bold.ttf",
				"tools/oracle/fonts/LiberationSans-Italic.ttf",
				"tools/oracle/fonts/LiberationSans-BoldItalic.ttf",
			]
		),
	];

	public static string Write(string repository, IReadOnlyList<FontFamily> families)
	{
		var text = new StringBuilder();
		text.Append("""
			// <auto-generated>
			// Generated by tools/SplashTheMusical.Upstream from the font files the families of FontTableWriter name.
			// Run mise run upstream-fonts to rewrite it.
			// </auto-generated>

			#nullable enable

			namespace SplashTheMusical.Text;

			internal static partial class FontTables
			{
				/// <summary>The number of families. Each family has four faces: regular, bold, italic and bold italic.</summary>
			""");
		text.Append(CultureInfo.InvariantCulture, $"\n\tpublic const int FamilyCount = {families.Count};\n\n");

		text.Append("""
				/// <summary>The index of the family a CSS family name names, compared ignoring case, or -1.</summary>
				public static int FindFamily(ReadOnlySpan<char> name)
				{

			""");
		for (var f = 0; f < families.Count; f++)
		{
			var names = string.Join(" || ", new[] { families[f].Name }.Concat(families[f].Aliases)
				.Select(name => $"name.Equals(\"{name}\", StringComparison.OrdinalIgnoreCase)"));
			text.Append(CultureInfo.InvariantCulture, $"\t\tif ({names})\n\t\t{{\n\t\t\treturn {f};\n\t\t}}\n\n");
		}

		text.Append("\t\treturn -1;\n\t}\n\n");

		// Faces with the same data share one property.
		var arrays = new List<(string Name, string Type, string Values)>();

		string Array(string name, string type, IEnumerable<string> values)
		{
			var joined = string.Join(", ", values);
			foreach (var existing in arrays)
			{
				if (existing.Type == type && existing.Values == joined)
				{
					return existing.Name;
				}
			}

			arrays.Add((name, type, joined));
			return name;
		}

		var faces = new List<string>();
		for (var f = 0; f < families.Count; f++)
		{
			for (var s = 0; s < 4; s++)
			{
				var path = Path.Combine(repository, families[f].Files[s]);
				var font = TrueTypeFont.Read(File.ReadAllBytes(path));
				var face = (4 * f) + s;
				var (starts, ends, offsets, advances) = Ranges(font.Advances);
				var fallback = (int)Math.Round("abcdefghijklmnopqrstuvwxyz".Average(c => font.Advances[c]));
				var kerning = font.Kerning.Where(pair => pair.Value != 0).ToList();
				string[] arguments =
				[
					Number(font.UnitsPerEm),
					Number(font.Ascender),
					Number(font.Descender),
					Number(fallback),
					Array($"RangeStarts{face}", "UInt16", starts.SelectMany(value => Bytes((ushort)value))),
					Array($"RangeEnds{face}", "UInt16", ends.SelectMany(value => Bytes((ushort)value))),
					Array($"RangeOffsets{face}", "UInt16", offsets.SelectMany(value => Bytes((ushort)value))),
					Array($"Advances{face}", "UInt16", advances.SelectMany(value => Bytes((ushort)value))),
					Array($"KerningPairs{face}", "UInt32", kerning.SelectMany(pair => Bytes(((uint)pair.Key.Left << 16) | pair.Key.Right))),
					Array($"KerningValues{face}", "Int16", kerning.SelectMany(pair => Bytes((ushort)(short)pair.Value))),
				];
				faces.Add($"\t\t{Number(face)} => new FontFace(\n\t\t\t{string.Join(",\n\t\t\t", arguments)}\n\t\t),");
			}
		}

		text.Append("""
				/// <summary>The face at <paramref name="index"/>: four times the family, plus 1 for bold and 2 for italic.</summary>
				public static FontFace Face(int index) => index switch
				{

			""");
		foreach (var face in faces)
		{
			text.Append(face).Append('\n');
		}

		text.Append("\t\t_ => throw new ArgumentOutOfRangeException(nameof(index)),\n\t};\n");

		foreach (var (name, type, values) in arrays)
		{
			text.Append(CultureInfo.InvariantCulture, $"\n\t/// <summary>{type} values, little-endian.</summary>\n\tprivate static ReadOnlySpan<byte> {name} =>\n\t[\n");
			foreach (var line in Lines(values))
			{
				text.Append("\t\t").Append(line).Append('\n');
			}

			text.Append("\t];\n");
		}

		text.Append("}\n");
		return text.ToString();
	}

	/// <summary>The runs of consecutive characters, and the advances of the characters in run order.</summary>
	private static (List<int> Starts, List<int> Ends, List<int> Offsets, List<int> Advances) Ranges(SortedDictionary<char, int> advances)
	{
		var starts = new List<int>();
		var ends = new List<int>();
		var offsets = new List<int>();
		var values = new List<int>();
		foreach (var (character, advance) in advances)
		{
			if (ends.Count == 0 || character != ends[^1] + 1)
			{
				starts.Add(character);
				ends.Add(character);
				offsets.Add(values.Count);
			}
			else
			{
				ends[^1] = character;
			}

			values.Add(advance);
		}

		return (starts, ends, offsets, values);
	}

	/// <summary>Splits a comma-separated list into lines of 16 values, each ending with a comma.</summary>
	private static IEnumerable<string> Lines(string values)
	{
		if (values.Length == 0)
		{
			yield break;
		}

		var items = values.Split(", ");
		for (var i = 0; i < items.Length; i += 16)
		{
			yield return string.Join(", ", items.Skip(i).Take(16)) + ",";
		}
	}

	private static IEnumerable<string> Bytes(ushort value) => [Number(value & 0xFF), Number(value >> 8)];

	private static IEnumerable<string> Bytes(uint value) => [.. Bytes((ushort)(value & 0xFFFF)), .. Bytes((ushort)(value >> 16))];

	private static string Number(int value) => value.ToString(CultureInfo.InvariantCulture);
}
