using System.Text;

namespace SplashTheMusical.Upstream;

/// <summary>
/// Writes <c>ConfigKeys</c>, the key names mermaid.js's <c>sanitizeDirective</c> keeps, from the <c>name</c> lines of the
/// oracle's corpus/config.txt. mermaid.js builds the set from its default config at run time, which holds the default
/// theme's variables, function defaults and keys that config.schema.yaml does not have, so the schema alone cannot give it.
/// </summary>
public static class ConfigKeysWriter
{
	private const string NamePrefix = "name\t";

	public static string Write(string configText, string version)
	{
		var header = "# mermaid " + version;
		var lines = configText.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');
		if (!lines.Contains(header))
		{
			throw new InvalidDataException($"corpus/config.txt is not from mermaid {version}. Run mise run corpus-oracle.");
		}

		var names = lines.Where(l => l.StartsWith(NamePrefix, StringComparison.Ordinal)).Select(l => l[NamePrefix.Length..]).Distinct().Order(StringComparer.Ordinal).ToList();
		if (names.Count == 0)
		{
			throw new InvalidDataException("corpus/config.txt has no name lines. Run mise run corpus-oracle.");
		}

		var code = new StringBuilder();
		code.Append("// <auto-generated>\n");
		code.Append($"// Generated by tools/SplashTheMusical.Upstream from the name lines of corpus/config.txt at mermaid@{version}.\n");
		code.Append("// Run mise run upstream-generate to rewrite it.\n");
		code.Append("// </auto-generated>\n\n");
		code.Append("#nullable enable\n\n");
		code.Append("namespace SplashTheMusical.Config;\n\n");
		code.Append("internal static partial class ConfigKeys\n{\n");
		code.Append("\t/// <summary>mermaid.js's <c>configKeys</c>, sorted by UTF-16 code unit.</summary>\n");
		code.Append("\tprivate static readonly string[] Names =\n\t[\n");
		foreach (var name in names)
		{
			code.Append("\t\t\"").Append(name.Replace("\\", "\\\\", StringComparison.Ordinal).Replace("\"", "\\\"", StringComparison.Ordinal)).Append("\",\n");
		}

		code.Append("\t];\n}\n");
		return code.ToString();
	}
}
